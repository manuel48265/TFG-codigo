# J. Runge, "Conditional independence testing based on a nearest-neighbor
# estimator of conditional mutual information," AISTATS 2018 (PMLR 84),
# arXiv:1709.01447. Statistic: Eq. 5. Null distribution: Algorithm 1.
# Differences from the paper, shared with tigramite's implementation:
# Y is permuted instead of X, ranks are ascending (smallest value = 0), and
# the p-value is (#{null >= statistic} + 1) / (B + 1) instead of Eq. 6.
# null_fit="gamma" is a tigramite option and is not in the paper.

from typing import Literal

import numpy as np
import pandas as pd
from numpy.typing import NDArray
from scipy import spatial, special, stats

from src.CI_tests.common import CIResult, ci_test


class CMIknn:
    """Conditional independence test based on a nearest-neighbor estimate of
    conditional mutual information (Runge, 2018).

    The statistic is the Frenzel-Pompe kNN estimator of I(X;Y|Z) (Eq. 5),
    computed on rank-transformed data. The null distribution is generated by
    permuting Y within neighborhoods of Z (Algorithm 1), or by plain
    permutation when Z is empty.

    Parameters
    ----------
    knn : int or float, optional (default: 0.2)
        Number of nearest neighbors of the estimator. Values below 1 are a
        fraction of the sample size (``knn * n``); values of 1 or more are an
        absolute count. The result is never below 1.

    k_perm : int, optional (default: 5)
        Number of nearest neighbors in Z from which each permuted value of Y
        is drawn. Ignored when Z is empty.

    sig_samples : int, optional (default: 50)
        Number of permutations used to build the null distribution.

    seed : int, optional (default: 0)
        Seed of the random generator used for the tie-breaking noise and
        the permutations.

    workers : int, optional (default: -1)
        Number of workers of the KD-tree queries. -1 uses all processors.

    tie_break_ulps : float or None, optional (default: None)
        Scale of the noise that breaks ties before ranking. If None, the
        noise is ``1e-6`` times the standard deviation of each column. If a
        number, the noise is that many floating-point ULPs of each value.

    null_fit : {'gamma', None}, optional (default: 'gamma')
        If 'gamma', a three-parameter Gamma distribution is fitted to the
        permutation statistics and the p-value is read from its survival
        function; the empirical p-value is used if the fit fails. If None,
        the p-value is ``(#{null >= statistic} + 1) / (sig_samples + 1)``.
    """

    def __init__(
        self,
        knn: int | float = 0.2,
        k_perm: int = 5,
        sig_samples: int = 50,
        seed: int = 0,
        workers: int = -1,
        tie_break_ulps: float | None = None,
        null_fit: Literal["gamma"] | None = "gamma",
    ) -> None:

        self.random_state = np.random.default_rng(seed=seed)
        self.knn = knn
        self.k_perm = k_perm
        self.sig_samples = sig_samples
        self.workers = workers
        self.tie_break_ulps = tie_break_ulps
        self.null_fit = null_fit

    ######################################################################################
    # Rank transform
    # we rank-transform the samples individually in
    # each dimension: Firstly, to avoid points with equal
    # distance, small amplitude random noise is added to break ties.

    # Then, for all n values x1 , . . . , xn , we
    # replace xi with the transformed value r, where r is
    # defined such that xi is the rth largest among all x values.

    # In the oficial implementation they have chosen ascensing order
    # intead of descending as they say in the paper.

    # tie_break_ulps=None (default) keeps the official implementation's
    # std-relative noise. Passing a number switches to np.spacing (the
    # float64 ULP at each value) scaled by that many ULPs instead: a
    # std-relative scale can be coarser than genuine near-ties that
    # nonlinear transforms can produce (found empirically: two values 3e-7
    # apart in a cubic/tanh-transformed column, well inside a 1e-6*std-scale
    # noise band on typical data) -- the noise then decides a real ordering
    # instead of only breaking ties, making the tie-break itself a source of
    # disagreement against any other implementation that tie-breaks
    # independently (e.g. tigramite, see
    # experiments/verification/verify_cmiknn.py). ULP-scaled noise can only
    # ever flip values already equal to within floating-point precision.
    def _rank_transform(self, data: NDArray[np.float64]) -> NDArray[np.float64]:
        if self.tie_break_ulps is None:
            noise_scale = 1e-6 * data.std(axis=0, keepdims=True)
        else:
            noise_scale = self.tie_break_ulps * np.abs(np.spacing(data))
        data = data + noise_scale * self.random_state.random(data.shape)
        return data.argsort(axis=0).argsort(axis=0).astype(np.float64)

    ######################################################################################
    # easier way to get the exact amount of neighbor we are going to use
    def _get_knn(self, sample_size: int) -> int:
        if self.knn < 1:
            return max(1, int(self.knn * sample_size))
        else:
            return max(1, int(self.knn))

    ######################################################################################
    # Equation 5 in the paper
    def _cmi_estimator(
        self, k: int, k_z: NDArray[np.int64], k_xz: NDArray[np.int64], k_yz: NDArray[np.int64]
    ) -> float:
        return special.digamma(k) + np.mean(
            special.digamma(k_z) - special.digamma(k_xz) - special.digamma(k_yz)
        )

    ######################################################################################
    # The main computational cost comes from
    # searching nearest neighbors in the high dimensional
    # subspaces which we speed up using KD-tree neighbor
    # search (Maneewongvatana and Mount, 1999). Hence,
    # the computational complexity will typically scale
    # less than quadratically with the sample size.

    def _neighbor_counts(
        self,
        x: NDArray[np.float64],
        y: NDArray[np.float64],
        z: NDArray[np.float64] | None,
        knn: int,
    ) -> tuple[NDArray[np.int64], NDArray[np.int64], NDArray[np.int64]]:
        size: int = x.shape[0]
        joint: NDArray[np.float64] = (
            np.column_stack((x, y, z)) if z is not None else np.column_stack((x, y))
        )
        tree = spatial.cKDTree(joint)
        eps = tree.query(joint, k=[knn + 1], p=np.inf, workers=self.workers)[0][:, 0].astype(
            np.float64
        )

        # From the original implementation
        # To search neighbors < eps instead of <= eps, we need to reduce eps by a bit
        eps = np.multiply(eps, 0.999999999)

        joint_x_z = np.column_stack((x, z)) if z is not None else x.reshape(-1, 1)
        k_xz = spatial.cKDTree(joint_x_z).query_ball_point(
            joint_x_z, r=eps, p=np.inf, return_length=True, workers=self.workers
        )

        joint_y_z = np.column_stack((y, z)) if z is not None else y.reshape(-1, 1)
        k_yz = spatial.cKDTree(joint_y_z).query_ball_point(
            joint_y_z, r=eps, p=np.inf, return_length=True, workers=self.workers
        )

        if z is not None:
            k_z = spatial.cKDTree(z).query_ball_point(
                z, r=eps, p=np.inf, return_length=True, workers=self.workers
            )
        else:
            k_z = np.full(size, size, dtype=np.float64)

        return k_xz, k_yz, k_z

    ######################################################################################
    # Cache optimization
    # Not in algorithm 1: k_perm nearest neighbors in Z for each sample.
    # Doesn't depend on which shuffle draw we're on — only on z, which is
    # fixed for the whole sig_samples loop in _calc_pvalue — so it's built
    # once and reused across every draw instead of once per draw.
    def _local_permutation_neighbors(self, z: NDArray[np.float64]) -> NDArray[np.int32]:
        return (
            spatial.cKDTree(z)
            .query(z, k=self.k_perm, p=np.inf, eps=0.0, workers=self.workers)[1]
            .astype(np.int32)
        )

    ######################################################################################
    # algorithm 1, given an already-built neighbor list (see
    # _local_permutation_neighbors). Shuffles it in place: each call still
    # draws a fresh, uniform per-row shuffle regardless of the array's
    # state going in, so reusing the same array across calls is safe.
    def _local_permutation(self, neighbors: NDArray[np.int32]) -> NDArray[np.int32]:
        for row in neighbors:
            self.random_state.shuffle(row)

        used = set()
        permutation = np.zeros(neighbors.shape[0], dtype=np.int32)
        for sample_index in self.random_state.permutation(neighbors.shape[0]).astype(np.int32):
            m = 0
            use = neighbors[sample_index, m]

            while (use in used) and (m < self.k_perm - 1):
                m += 1
                use = neighbors[sample_index, m]

            permutation[sample_index] = use
            used.add(use)

        return permutation

    ######################################################################################
    # Equation 6:
    def _calc_pvalue(
        self,
        x: NDArray[np.float64],
        y: NDArray[np.float64],
        z: NDArray[np.float64] | None,
        value: float,
        knn: int,
    ) -> float:
        sample_size = y.shape[0]
        null_dist = np.zeros(self.sig_samples)
        neighbors = self._local_permutation_neighbors(z) if z is not None else None

        for b in range(self.sig_samples):
            if neighbors is None:
                perm = self.random_state.permutation(sample_size).astype(np.int32)
            else:
                perm = self._local_permutation(neighbors)

            y_perm = y[perm]
            k_xz, k_yz, k_z = self._neighbor_counts(x, y_perm, z, knn)
            null_dist[b] = self._cmi_estimator(knn, k_z, k_xz, k_yz)

        # null_fit="gamma" (tigramite's own null_fit option): fits a Gamma to
        # null_dist and reads the p-value off its CDF instead of counting
        # exceedances, so sig_samples can drop from ~500 to ~50 for the same
        # tail accuracy -- counting needs many draws to resolve a small
        # empirical p-value, a smooth fit doesn't.
        if self.null_fit == "gamma":
            try:
                a, loc, scale = stats.gamma.fit(null_dist)
                return float(1.0 - stats.gamma.cdf(value, a, loc=loc, scale=scale))
            except Exception:
                pass

        # Empirical Monte Carlo
        pval = float(np.sum(null_dist >= value) + 1) / (self.sig_samples + 1)

        return pval

    ######################################################################################
    def test(
        self,
        x: NDArray[np.float64],
        y: NDArray[np.float64],
        z: NDArray[np.float64] | None = None,
        alpha: float = 0.05,
    ) -> CIResult:
        """Test whether X and Y are conditionally independent given Z.

        Parameters
        ----------
        x : ndarray of shape (n,)
            Sample of X.

        y : ndarray of shape (n,)
            Sample of Y.

        z : ndarray of shape (n, d_z) or None, optional (default: None)
            Sample of the conditioning set. If None, the test is marginal.

        alpha : float, optional (default: 0.05)
            Significance level; the test rejects if ``p_value < alpha``.

        Returns
        -------
        result : CIResult
            ``statistic`` is the estimated CMI, ``p_value`` the permutation
            p-value and ``reject`` the decision at level ``alpha``.
        """
        x, y, z = (
            self._rank_transform(x),
            self._rank_transform(y),
            self._rank_transform(z) if z is not None else None,
        )
        sample_size = y.shape[0]
        knn = self._get_knn(sample_size)
        k_xz, k_yz, k_z = self._neighbor_counts(x, y, z, knn)
        value = self._cmi_estimator(knn, k_z, k_xz, k_yz)
        p_value = self._calc_pvalue(x, y, z, value, knn)
        return CIResult(statistic=value, p_value=p_value, reject=(p_value < alpha))


@ci_test
def cmiknn_test(
    data: pd.DataFrame,
    x: str,
    y: str,
    z: list[str] | None = None,
    alpha: float = 0.05,
    **kwargs: object,
) -> CIResult:
    """Test conditional independence of two columns given others with the kNN CMI test.

    Wrapper that builds a ``CMIknn`` from ``kwargs`` and runs its test.

    Parameters
    ----------
    data : DataFrame
        Observations in rows, numeric variables in columns.

    x : str
        Name of the first tested column.

    y : str
        Name of the second tested column.

    z : list of str or None, optional (default: None)
        Names of the conditioning columns. If None or empty, the test is marginal.

    alpha : float, optional (default: 0.05)
        Significance level; the test rejects if ``p_value < alpha``.

    **kwargs :
        Constructor arguments of ``CMIknn`` (``knn``, ``k_perm``,
        ``sig_samples``, ``seed``, ``workers``, ``tie_break_ulps``,
        ``null_fit``).

    Returns
    -------
    result : CIResult
        ``statistic`` is the estimated CMI, ``p_value`` the permutation
        p-value and ``reject`` the decision at level ``alpha``.
    """
    z_values = data[z].to_numpy(dtype=np.float64) if z else None
    return CMIknn(**kwargs).test(  # type: ignore[arg-type]
        data[x].to_numpy(dtype=np.float64), data[y].to_numpy(dtype=np.float64), z_values, alpha
    )
